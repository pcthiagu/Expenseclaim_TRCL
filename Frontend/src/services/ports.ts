import type { PolicyConfig } from '../config/policy';
import type {
  AttachmentMeta, ClaimLine, EligibilityEnforcement, Employee, ExpenseClaim, LimitPer, RecordKind, Receipt, ReferenceData, Role, TrailEvent, TravelClaimRecord,
} from '../types/domain';

/**
 * The operations the UI needs from "the backend", expressed as a typed interface.
 *
 * STATUS: INTERFACE ONLY. No endpoint path, HTTP verb, request body or response shape is implied
 * here because the real backend contract was not supplied (docs/02-api-gaps.md lists every operation
 * with its status). An implementation (e.g. HttpGateway) must be written against the real contract
 * and translate to/from the UI types in src/types/domain.ts. Until then the app has NO production
 * data source: there is no mock data; every operation is answered by the stored procedures.
 *
 * Authority rules the implementation must respect (and the backend must enforce):
 *  - identity and role come from the authenticated session, never from client-supplied fields;
 *  - request numbers are generated by the backend at first save;
 *  - approved amounts, status transitions and ownership are validated server-side.
 */

export interface SessionUser {
  code: string;
  name: string;
  role: Role;
  /** True when the person is ALSO an approver: the app then offers a switch between the Employee and Approver views. */
  isApprover?: boolean;
  /** Revision stamp of each installed SQL script (TA_SchemaVersion), compared with what this build expects. */
  schema?: Record<string, string>;
  designation?: string;
  department?: string;
  costCentre?: string;
}

export interface PolicySnapshot {
  policy: PolicyConfig;
}

export interface LocationPolicyLimit {
  limit: number | null;
  limitPer?: LimitPer | null;
  enforceEligibility?: EligibilityEnforcement;
}

export interface RecordQuery {
  kind?: RecordKind;
  /** Only meaningful for approvers who are authorised to read other employees' records. */
  employeeCode?: string;
  status?: string;
  search?: string;
  from?: string;
  to?: string;
  page?: number;
  pageSize?: number;
  sortKey?: string;
  sortDir?: 'asc' | 'desc';
}

export interface Page<T> { rows: T[]; total: number }

export interface ApprovalDecision {
  /** Per-line approved amounts and remarks for claims. */
  lines?: Array<Pick<ClaimLine, 'id' | 'approvedAmount' | 'approverRemarks'>>;
  approverComments?: string;
  approverRemarks?: string;
  rejectionReason?: string;
}

export interface TravelClaimGateway {
  getSession(): Promise<SessionUser>;
  /** Tells the backend which VIEW following calls act in. An approver in the 'employee' view is treated as an ordinary employee (it can only narrow, never grant rights). */
  setViewMode?(mode: Role): void;
  getPolicy(): Promise<PolicySnapshot | null>;
  /** Location-specific item ceiling from TA_usp_GetLocationPolicyLimit. */
  getLocationPolicyLimit(itemKey: string, stayLocation: string, billAvailable?: 'Yes' | 'No'): Promise<LocationPolicyLimit | null>;
  /** Field definitions, expense types, items and option lists: the screens contain none of these. */
  getReferenceData(): Promise<ReferenceData>;
  /** Who created, submitted and decided the request, with the decision text. */
  getApprovalTrail(kind: RecordKind, id: string): Promise<TrailEvent[]>;

  listRecords(q: RecordQuery): Promise<Page<TravelClaimRecord>>;
  getRecord(kind: RecordKind, id: string): Promise<TravelClaimRecord>;
  /** Creates (no number yet) or updates a draft. The backend assigns requestNumber on first save. */
  saveDraft(record: TravelClaimRecord): Promise<TravelClaimRecord>;
  submit(kind: RecordKind, id: string): Promise<TravelClaimRecord>;
  deleteDraft(kind: RecordKind, id: string): Promise<void>;
  copyRejectedClaim(id: string): Promise<ExpenseClaim>;

  approve(kind: RecordKind, id: string, decision: ApprovalDecision): Promise<TravelClaimRecord>;
  reject(kind: RecordKind, id: string, decision: ApprovalDecision): Promise<TravelClaimRecord>;
  listPendingApprovals(): Promise<TravelClaimRecord[]>;
  listApprovalHistory(days: number): Promise<TravelClaimRecord[]>;

  listReceipts(): Promise<Receipt[]>;
  uploadReceipts(files: File[]): Promise<Receipt[]>;
  updateReceipt(receipt: Receipt): Promise<Receipt>;
  deleteReceipt(id: string): Promise<void>;

  /** Uploads a file for a record/line and returns its stored metadata. */
  uploadAttachment(file: File, target?: { kind?: RecordKind; recordId?: string; lineId?: string }): Promise<AttachmentMeta>;
  openAttachment(att: AttachmentMeta): Promise<Blob>;

  lookupEmployees(query: string): Promise<Employee[]>;
}

/** Operations whose backend support is unverified, for docs and for a startup capability check. */
export const REQUIRED_OPERATIONS = [
  'getSession', 'getPolicy', 'listRecords', 'getRecord', 'saveDraft', 'submit', 'deleteDraft', 'copyRejectedClaim',
  'approve', 'reject', 'listPendingApprovals', 'listApprovalHistory',
  'listReceipts', 'uploadReceipts', 'updateReceipt', 'deleteReceipt',
  'uploadAttachment', 'openAttachment', 'lookupEmployees',
] as const satisfies ReadonlyArray<keyof TravelClaimGateway>;
